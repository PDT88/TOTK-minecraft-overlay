typedef struct {
    uint8_t *rgba;        /* Straight RGBA8888, top-to-bottom row-major (width * height * 4 bytes) */
    int width;
    int height;
    int loaded;
    const char *rel_path; /* e.g. "textures/gui/hotbar.png" */
} McTexture;

typedef struct {
    int16_t *pcm;         /* Signed 16-bit interleaved PCM (frames * channels samples) */
    uint32_t frames;      /* Number of sample frames */
    uint32_t sample_rate; /* 48000 Hz */
    uint16_t channels;    /* 1 = mono, 2 = stereo */
    uint16_t loaded;
    const char *rel_path; /* e.g. "sounds/random/explode1.wav" */
} McSound;

typedef struct {
    int textures_loaded;
    int textures_total;
    int sounds_loaded;
    int sounds_total;
    int en_us_loaded;
    int font_widths_loaded;
    char root_dir[1024];
} McAssetStats;

/* Thread-safe idempotent initializer. Pass NULL to auto-resolve assets/mc/ relative to
   TOTK_MC_ASSETS env var, executable directory, %APPDATA%, or cwd.
   Returns 1 if core assets loaded, 0 on failure. Must be called outside real-time audio callbacks. */
int mc_assets_init(const char *override_dir);

/* Lock-free atomic readiness check (safe inside audio output pull/mix callbacks). */
int mc_assets_ready(void);

/* Releases heap buffers allocated by mc_assets_init (for standalone tools/tests). */
void mc_assets_shutdown(void);

const char *mc_assets_root_dir(void);
void mc_assets_get_stats(McAssetStats *out_stats);

/* Lock-free read-only accessors once mc_assets_ready() == 1. */
const McTexture *mc_asset_tex(McTextureId id);
const McTexture *mc_asset_tex_by_path(const char *rel_path);

const McSound *mc_asset_sound(McSoundId id);
int mc_asset_sound_group_count(McSoundGroupId group);
const McSound *mc_asset_sound_group_get(McSoundGroupId group, int index);
const McSound *mc_asset_sound_group_pick(McSoundGroupId group, uint32_t seed);

/* 256-entry Mojangles glyph advance width table (8px base glyph height). */
const uint8_t *mc_asset_font_widths(void);
int mc_asset_measure_text(const char *text);

/* Official English (en_us.json) string lookup (e.g. "item.minecraft.firework_rocket"). */
const char *mc_asset_en_us(const char *lang_key);

static inline uint32_t mc_asset_tex_pixel(const McTexture *t, int x, int y) {
    if (!t || !t->loaded || !t->rgba) return 0u;
    if ((unsigned)x >= (unsigned)t->width || (unsigned)y >= (unsigned)t->height) return 0u;
    const uint8_t *p = t->rgba + ((size_t)y * (size_t)t->width + (size_t)x) * 4u;
    return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
}

